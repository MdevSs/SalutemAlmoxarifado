-- Banco novo da aplicação Salutem. Executar APENAS na base local vazia criada para este sistema.
-- Este arquivo NÃO contém schema do ERP e não deve ser aplicado em 192.168.1.2.
-- Tabelas de negócio: setores e requisicoes. Itens/eventos ficam em JSONB.

CREATE SEQUENCE IF NOT EXISTS public.salutem_itecontrol_seq AS bigint START WITH 84333 INCREMENT BY 1 NO CYCLE;

CREATE TABLE IF NOT EXISTS public.setores (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(120) NOT NULL UNIQUE,
    perfil varchar(24) NOT NULL,
    lider_nome varchar(120),
    senha_hash text NOT NULL,
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_setores_nome_nonempty CHECK (length(trim(nome)) > 0),
    CONSTRAINT ck_setores_perfil CHECK (perfil IN ('solicitante', 'almoxarifado', 'administrador')),
    CONSTRAINT ck_setores_lider_por_perfil CHECK (
        (perfil = 'solicitante' AND lider_nome IS NOT NULL AND length(trim(lider_nome)) > 0)
        OR (perfil IN ('almoxarifado', 'administrador') AND lider_nome IS NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_setores_nome_ci
    ON public.setores (lower(btrim(nome)));
CREATE UNIQUE INDEX IF NOT EXISTS uq_setores_almoxarifado_single
    ON public.setores (perfil) WHERE perfil = 'almoxarifado';
CREATE UNIQUE INDEX IF NOT EXISTS uq_setores_administrador_single
    ON public.setores (perfil) WHERE perfil = 'administrador';

CREATE TABLE IF NOT EXISTS public.requisicoes (
    itecontrol bigint PRIMARY KEY,
    setor_id bigint NOT NULL REFERENCES public.setores(id) ON DELETE RESTRICT,
    setor_nome_snapshot varchar(120) NOT NULL,
    lider_nome_snapshot varchar(120) NOT NULL,
    data_requisicao date NOT NULL,
    instrucoes_entrega text NOT NULL DEFAULT '',
    status varchar(24) NOT NULL DEFAULT 'Pendente',
    observacoes_almoxarifado text NOT NULL DEFAULT '',
    responsavel_confirmacao varchar(120),
    itens jsonb NOT NULL DEFAULT '[]'::jsonb CONSTRAINT ck_requisicoes_itens_array CHECK (jsonb_typeof(itens) = 'array'),
    eventos jsonb NOT NULL DEFAULT '[]'::jsonb CONSTRAINT ck_requisicoes_eventos_array CHECK (jsonb_typeof(eventos) = 'array'),
    erp_status varchar(24) NOT NULL DEFAULT 'aguardando'
    erp_enviado_em timestamptz,
    erp_erro text,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now(),
    finalizado_em timestamptz,
    -- CONSTRAINT ck_requisicoes_status
    --     CHECK (status IN ('Pendente', 'Em andamento', 'Finalizada', 'Parcial'))
);

CREATE INDEX IF NOT EXISTS ix_requisicoes_setor_criado
    ON public.requisicoes (setor_id, criado_em DESC);
CREATE INDEX IF NOT EXISTS ix_requisicoes_status_criado
    ON public.requisicoes (status, criado_em DESC);
CREATE INDEX IF NOT EXISTS ix_requisicoes_data_criado
    ON public.requisicoes (data_requisicao DESC, criado_em DESC);

-- Protege instalações/reexecuções contra sequence abaixo do maior controle já gravado.
SELECT setval(
    'public.salutem_itecontrol_seq',
    GREATEST(
        COALESCE((SELECT max(itecontrol) FROM public.requisicoes), 84332),
        COALESCE(pg_sequence_last_value('public.salutem_itecontrol_seq'::regclass), 84332),
        84332
    ),
    true
);
